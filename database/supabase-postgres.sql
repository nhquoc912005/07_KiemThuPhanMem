-- Run this file in Supabase SQL Editor. It intentionally does not create a database.

BEGIN;

DROP TABLE IF EXISTS route_plan_logs CASCADE;
DROP TABLE IF EXISTS route_plan_driver_assignments CASCADE;
DROP TABLE IF EXISTS route_plan_vehicle_assignments CASCADE;
DROP TABLE IF EXISTS route_plan_customers CASCADE;
DROP TABLE IF EXISTS route_plans CASCADE;
DROP TABLE IF EXISTS import_logs CASCADE;
DROP TABLE IF EXISTS source_metadata CASCADE;
DROP TABLE IF EXISTS external_vehicles CASCADE;
DROP TABLE IF EXISTS external_drivers CASCADE;
DROP TABLE IF EXISTS external_customers CASCADE;
DROP TABLE IF EXISTS TheoDoiTrangThai CASCADE;
DROP TABLE IF EXISTS ChiTietLoTrinh CASCADE;
DROP TABLE IF EXISTS LoTrinhTrungChuyen CASCADE;
DROP TABLE IF EXISTS VeTrungChuyen CASCADE;
DROP TABLE IF EXISTS KhachHang CASCADE;
DROP TABLE IF EXISTS XeTrungChuyen CASCADE;
DROP TABLE IF EXISTS TaiXe CASCADE;
DROP TABLE IF EXISTS NhanVienDieuPhoi CASCADE;
DROP TABLE IF EXISTS TaiKhoanNguoiDung CASCADE;

CREATE TABLE TaiKhoanNguoiDung (
  MaTaiKhoan integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TenDangNhap varchar(50) NOT NULL UNIQUE,
  MatKhauMaHoa varchar(255) NOT NULL,
  SoDienThoai varchar(15) NULL,
  VaiTro varchar(30) NULL,
  TrangThaiTaiKhoan boolean NOT NULL DEFAULT TRUE,
  YeuCauDoiMatKhau boolean NOT NULL DEFAULT FALSE,
  SoLanDangNhapSai integer NOT NULL DEFAULT 0,
  KhoaTamThoiDenLuc timestamp NULL,
  NgayTao timestamp NOT NULL DEFAULT NOW()
);

CREATE TABLE NhanVienDieuPhoi (
  MaNhanVien integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  HoTen varchar(100) NOT NULL,
  SoDienThoai varchar(15) NULL,
  TrangThai varchar(30) NULL,
  MaTaiKhoan integer NULL REFERENCES TaiKhoanNguoiDung(MaTaiKhoan)
);

CREATE TABLE TaiXe (
  MaTaiXe integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  MaNhanVienTaiXe varchar(20) NULL,
  HoTen varchar(100) NOT NULL,
  SoDienThoai varchar(15) NOT NULL UNIQUE,
  CCCD varchar(20) NOT NULL UNIQUE,
  LoaiBangLai varchar(50) NULL,
  TrangThaiTaiXe varchar(30) NULL,
  MaTaiKhoan integer NULL REFERENCES TaiKhoanNguoiDung(MaTaiKhoan)
);

CREATE TABLE XeTrungChuyen (
  MaXe integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  BienSo varchar(50) NOT NULL UNIQUE,
  LoaiXe varchar(50) NOT NULL,
  SoCho integer NOT NULL,
  TrangThaiXe varchar(30) NULL,
  CONSTRAINT ck_xetrungchuyen_socho CHECK (SoCho BETWEEN 4 AND 45)
);

CREATE TABLE KhachHang (
  MaKhachHang integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TenKhachHang varchar(100) NOT NULL,
  SoDienThoai varchar(15) NOT NULL UNIQUE,
  DiaChiDon varchar(255) NOT NULL,
  DiaChiDonLat numeric(10,7) NULL,
  DiaChiDonLng numeric(10,7) NULL,
  DiaChiTra varchar(255) NOT NULL,
  DiaChiTraLat numeric(10,7) NULL,
  DiaChiTraLng numeric(10,7) NULL,
  TrangThai varchar(30) NULL
);

CREATE TABLE VeTrungChuyen (
  MaVe integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  KhungGioTrungChuyen varchar(100) NULL,
  SoLuongGhe integer NOT NULL,
  TrangThaiVe varchar(50) NOT NULL,
  MaKhachHang integer NOT NULL REFERENCES KhachHang(MaKhachHang),
  CONSTRAINT ck_vetrungchuyen_soluongghe CHECK (SoLuongGhe BETWEEN 1 AND 10)
);

CREATE TABLE LoTrinhTrungChuyen (
  MaLoTrinh integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ThoiGianBatDau timestamp NOT NULL,
  ThoiGianKetThuc timestamp NULL,
  LoTrinhDuKien text NULL,
  GhiChu text NULL,
  TrangThaiLoTrinh varchar(50) NOT NULL,
  MaXe integer NOT NULL REFERENCES XeTrungChuyen(MaXe),
  MaTaiXe integer NOT NULL REFERENCES TaiXe(MaTaiXe),
  MaNhanVien integer NOT NULL REFERENCES NhanVienDieuPhoi(MaNhanVien),
  CONSTRAINT ck_lotrinh_thoigian CHECK (ThoiGianKetThuc IS NULL OR ThoiGianKetThuc >= ThoiGianBatDau)
);

CREATE TABLE ChiTietLoTrinh (
  MaChiTiet integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ThuTuDonTra integer NOT NULL,
  DiemDon varchar(255) NOT NULL,
  DiemDonLat numeric(10,7) NULL,
  DiemDonLng numeric(10,7) NULL,
  DiemTra varchar(255) NOT NULL,
  DiemTraLat numeric(10,7) NULL,
  DiemTraLng numeric(10,7) NULL,
  ThoiGianDonDuKien timestamp NULL,
  TrangThaiKhach varchar(50) NULL,
  MaLoTrinh integer NOT NULL REFERENCES LoTrinhTrungChuyen(MaLoTrinh),
  MaVe integer NOT NULL REFERENCES VeTrungChuyen(MaVe)
);

CREATE TABLE TheoDoiTrangThai (
  MaTheoDoi integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ViTriHienTai varchar(255) NULL,
  ThoiDiemCapNhat timestamp NOT NULL DEFAULT NOW(),
  TrangThai varchar(50) NULL,
  MaLoTrinh integer NOT NULL REFERENCES LoTrinhTrungChuyen(MaLoTrinh)
);

CREATE UNIQUE INDEX ux_taikhoannguoidung_sodienthoai
  ON TaiKhoanNguoiDung(SoDienThoai)
  WHERE SoDienThoai IS NOT NULL;

CREATE UNIQUE INDEX ux_taixe_manhanvientaixe
  ON TaiXe(MaNhanVienTaiXe)
  WHERE MaNhanVienTaiXe IS NOT NULL;

CREATE INDEX ix_lotrinh_taixe_trangthai_time
  ON LoTrinhTrungChuyen(MaTaiXe, TrangThaiLoTrinh, ThoiGianBatDau);

CREATE INDEX ix_lotrinh_xe_trangthai_time
  ON LoTrinhTrungChuyen(MaXe, TrangThaiLoTrinh, ThoiGianBatDau);

CREATE INDEX ix_ve_khachhang_trangthai
  ON VeTrungChuyen(MaKhachHang, TrangThaiVe);

CREATE INDEX ix_chitiet_lotrinh_thutu
  ON ChiTietLoTrinh(MaLoTrinh, ThuTuDonTra);

CREATE TABLE external_customers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_ma_khach_hang integer NOT NULL UNIQUE,
  customer_code varchar(20) NOT NULL UNIQUE,
  full_name varchar(100) NOT NULL,
  phone varchar(15) NOT NULL UNIQUE,
  default_pickup_address varchar(255) NULL,
  default_dropoff_address varchar(255) NULL,
  status varchar(20) NOT NULL DEFAULT 'ACTIVE',
  is_active boolean NOT NULL DEFAULT TRUE,
  created_at timestamp NOT NULL DEFAULT NOW(),
  updated_at timestamp NOT NULL DEFAULT NOW(),
  CONSTRAINT ck_external_customers_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX ix_external_customers_phone ON external_customers(phone);

CREATE TABLE external_drivers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_ma_tai_xe integer NOT NULL UNIQUE,
  driver_code varchar(20) NOT NULL UNIQUE,
  employee_code varchar(20) NULL,
  full_name varchar(100) NOT NULL,
  phone varchar(15) NOT NULL UNIQUE,
  national_id varchar(20) NOT NULL UNIQUE,
  license_no varchar(30) NULL,
  license_class varchar(50) NULL,
  work_status varchar(20) NOT NULL DEFAULT 'ACTIVE',
  availability_status varchar(20) NOT NULL DEFAULT 'AVAILABLE',
  is_active boolean NOT NULL DEFAULT TRUE,
  created_at timestamp NOT NULL DEFAULT NOW(),
  updated_at timestamp NOT NULL DEFAULT NOW(),
  CONSTRAINT ck_external_drivers_work_status CHECK (work_status IN ('ACTIVE', 'INACTIVE')),
  CONSTRAINT ck_external_drivers_availability CHECK (availability_status IN ('AVAILABLE', 'ASSIGNED', 'BUSY', 'OFF'))
);

CREATE UNIQUE INDEX ux_external_drivers_employee_code
  ON external_drivers(employee_code)
  WHERE employee_code IS NOT NULL;

CREATE INDEX ix_external_drivers_availability_status ON external_drivers(availability_status);

CREATE TABLE external_vehicles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_ma_xe integer NOT NULL UNIQUE,
  vehicle_code varchar(20) NOT NULL UNIQUE,
  plate_number varchar(20) NOT NULL UNIQUE,
  vehicle_type varchar(50) NULL,
  capacity integer NOT NULL,
  seat_count integer NOT NULL,
  operational_status varchar(20) NOT NULL DEFAULT 'ACTIVE',
  availability_status varchar(20) NOT NULL DEFAULT 'AVAILABLE',
  is_active boolean NOT NULL DEFAULT TRUE,
  created_at timestamp NOT NULL DEFAULT NOW(),
  updated_at timestamp NOT NULL DEFAULT NOW(),
  CONSTRAINT ck_external_vehicles_capacity CHECK (capacity > 0),
  CONSTRAINT ck_external_vehicles_seat_count CHECK (seat_count > 0),
  CONSTRAINT ck_external_vehicles_operational CHECK (operational_status IN ('ACTIVE', 'INACTIVE')),
  CONSTRAINT ck_external_vehicles_availability CHECK (availability_status IN ('AVAILABLE', 'ASSIGNED', 'ON_TRIP', 'MAINTENANCE'))
);

CREATE INDEX ix_external_vehicles_availability_status ON external_vehicles(availability_status);

CREATE TABLE route_plans (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_code varchar(30) NOT NULL UNIQUE,
  planned_start_at timestamp NOT NULL,
  planned_end_at timestamp NULL,
  status varchar(20) NOT NULL DEFAULT 'DRAFT',
  notes varchar(500) NULL,
  created_by varchar(50) NULL,
  created_at timestamp NOT NULL DEFAULT NOW(),
  updated_at timestamp NOT NULL DEFAULT NOW(),
  CONSTRAINT ck_route_plans_status CHECK (status IN ('DRAFT', 'CONFIRMED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED'))
);

CREATE INDEX ix_route_plans_planned_start_at ON route_plans(planned_start_at);

CREATE TABLE route_plan_customers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_plan_id bigint NOT NULL REFERENCES route_plans(id),
  external_customer_id integer NOT NULL REFERENCES external_customers(id),
  sequence_no integer NOT NULL,
  customer_code_snapshot varchar(20) NOT NULL,
  customer_name_snapshot varchar(100) NOT NULL,
  customer_phone_snapshot varchar(15) NOT NULL,
  pickup_address_snapshot varchar(255) NOT NULL,
  dropoff_address_snapshot varchar(255) NOT NULL,
  note varchar(255) NULL,
  created_at timestamp NOT NULL DEFAULT NOW(),
  updated_at timestamp NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_route_plan_customers_plan_sequence UNIQUE (route_plan_id, sequence_no),
  CONSTRAINT ck_route_plan_customers_sequence CHECK (sequence_no > 0)
);

CREATE INDEX ix_route_plan_customers_plan_seq ON route_plan_customers(route_plan_id, sequence_no);

CREATE TABLE route_plan_vehicle_assignments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_plan_id bigint NOT NULL REFERENCES route_plans(id),
  external_vehicle_id integer NOT NULL REFERENCES external_vehicles(id),
  assignment_status varchar(20) NOT NULL DEFAULT 'SELECTED',
  assigned_at timestamp NOT NULL DEFAULT NOW(),
  vehicle_code_snapshot varchar(20) NOT NULL,
  vehicle_plate_snapshot varchar(20) NOT NULL,
  vehicle_type_snapshot varchar(50) NULL,
  vehicle_capacity_snapshot integer NOT NULL,
  vehicle_seat_count_snapshot integer NOT NULL,
  created_at timestamp NOT NULL DEFAULT NOW(),
  updated_at timestamp NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_route_plan_vehicle_assignments_plan_vehicle UNIQUE (route_plan_id, external_vehicle_id),
  CONSTRAINT ck_route_plan_vehicle_assignments_status CHECK (assignment_status IN ('SELECTED', 'CONFIRMED', 'REPLACED'))
);

CREATE INDEX ix_route_plan_vehicle_assignments_plan ON route_plan_vehicle_assignments(route_plan_id);

CREATE TABLE route_plan_driver_assignments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_plan_id bigint NOT NULL REFERENCES route_plans(id),
  external_driver_id integer NOT NULL REFERENCES external_drivers(id),
  route_plan_vehicle_assignment_id bigint NULL REFERENCES route_plan_vehicle_assignments(id),
  assignment_status varchar(20) NOT NULL DEFAULT 'SELECTED',
  assigned_at timestamp NOT NULL DEFAULT NOW(),
  driver_code_snapshot varchar(20) NOT NULL,
  driver_name_snapshot varchar(100) NOT NULL,
  driver_phone_snapshot varchar(15) NOT NULL,
  driver_national_id_snapshot varchar(20) NULL,
  driver_license_no_snapshot varchar(30) NULL,
  driver_license_class_snapshot varchar(50) NULL,
  created_at timestamp NOT NULL DEFAULT NOW(),
  updated_at timestamp NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_route_plan_driver_assignments_plan_driver UNIQUE (route_plan_id, external_driver_id),
  CONSTRAINT ck_route_plan_driver_assignments_status CHECK (assignment_status IN ('SELECTED', 'CONFIRMED', 'REPLACED'))
);

CREATE INDEX ix_route_plan_driver_assignments_plan ON route_plan_driver_assignments(route_plan_id);

CREATE TABLE source_metadata (
  source_system varchar(30) PRIMARY KEY,
  source_name varchar(100) NOT NULL,
  description varchar(255) NULL,
  last_import_at timestamp NULL,
  created_at timestamp NOT NULL DEFAULT NOW(),
  updated_at timestamp NOT NULL DEFAULT NOW()
);

CREATE TABLE import_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_system varchar(30) NOT NULL,
  entity_type varchar(30) NOT NULL,
  total_records integer NOT NULL DEFAULT 0,
  succeeded_records integer NOT NULL DEFAULT 0,
  failed_records integer NOT NULL DEFAULT 0,
  status varchar(20) NOT NULL DEFAULT 'SUCCESS',
  started_at timestamp NOT NULL DEFAULT NOW(),
  finished_at timestamp NULL,
  error_message text NULL
);

CREATE TABLE route_plan_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_plan_id bigint NOT NULL REFERENCES route_plans(id),
  event_type varchar(50) NOT NULL,
  message varchar(500) NULL,
  payload jsonb NULL,
  created_by varchar(50) NULL,
  created_at timestamp NOT NULL DEFAULT NOW()
);

CREATE INDEX ix_route_plan_logs_plan_time ON route_plan_logs(route_plan_id, created_at);

