  INSERT INTO route_plans (plan_code, planned_start_at, planned_end_at, status, notes, created_by)
  VALUES ('RP0001', NOW() + INTERVAL '2 hours', NOW() + INTERVAL '4 hours', 'CONFIRMED', 'Kế hoạch điều phối demo [legacy_route_id=1]', 'dieuphoi1')
  RETURNING id
),
customer_seed AS (
  SELECT ec.*, row_number() OVER (ORDER BY ec.id) AS seq
  FROM external_customers ec
  WHERE ec.phone IN ('0389123456', '0389123452')
),
vehicle_seed AS (
  SELECT * FROM external_vehicles WHERE plate_number = '51A-12345' LIMIT 1
),
driver_seed AS (
  SELECT * FROM external_drivers WHERE phone = '0912345678' LIMIT 1
),
vehicle_assignment_seed AS (
  INSERT INTO route_plan_vehicle_assignments (
    route_plan_id,
    external_vehicle_id,
    assignment_status,
    vehicle_code_snapshot,
    vehicle_plate_snapshot,
    vehicle_type_snapshot,
    vehicle_capacity_snapshot,
    vehicle_seat_count_snapshot
  )
  SELECT
    plan_seed.id,
    vehicle_seed.id,
    'CONFIRMED',
    vehicle_seed.vehicle_code,
    vehicle_seed.plate_number,
    vehicle_seed.vehicle_type,
    vehicle_seed.capacity,
    vehicle_seed.seat_count
  FROM plan_seed
  CROSS JOIN vehicle_seed
  RETURNING id, route_plan_id
),
driver_assignment_seed AS (
  INSERT INTO route_plan_driver_assignments (
    route_plan_id,
    external_driver_id,
    route_plan_vehicle_assignment_id,
    assignment_status,
    driver_code_snapshot,
    driver_name_snapshot,
    driver_phone_snapshot,
    driver_national_id_snapshot,
    driver_license_no_snapshot,
    driver_license_class_snapshot
  )
  SELECT
    vehicle_assignment_seed.route_plan_id,
    driver_seed.id,
    vehicle_assignment_seed.id,
    'CONFIRMED',
    driver_seed.driver_code,
    driver_seed.full_name,
    driver_seed.phone,
    driver_seed.national_id,
    driver_seed.license_no,
    driver_seed.license_class
  FROM vehicle_assignment_seed
  CROSS JOIN driver_seed
  RETURNING route_plan_id
)
INSERT INTO route_plan_customers (
